window.BuilderRenderManager = {

    /*
    |--------------------------------------------------------------------------
    | Render Scheduled
    |--------------------------------------------------------------------------
    */

    scheduled: false,

    /*
    |--------------------------------------------------------------------------
    | Request Render
    |--------------------------------------------------------------------------
    */

    requestRender() {

        /*
        |--------------------------------------------------------------------------
        | Prevent Render Spam
        |--------------------------------------------------------------------------
        */

        if (this.scheduled) {
            return;
        }

        this.scheduled = true;

        /*
        |--------------------------------------------------------------------------
        | Next Frame Render
        |--------------------------------------------------------------------------
        */

        requestAnimationFrame(() => {

            /*
            |--------------------------------------------------------------------------
            | Render
            |--------------------------------------------------------------------------
            */

            if (window.BuilderCanvas) {

                BuilderCanvas.render();

            }

            /*
            |--------------------------------------------------------------------------
            | Reset
            |--------------------------------------------------------------------------
            */

            this.scheduled = false;

        });

    }

};