window.BuilderEventBus = {

    /*
    |--------------------------------------------------------------------------
    | Events
    |--------------------------------------------------------------------------
    */

    events: {},

    /*
    |--------------------------------------------------------------------------
    | Listen
    |--------------------------------------------------------------------------
    */

    on(event, callback) {

        /*
        |--------------------------------------------------------------------------
        | Init Array
        |--------------------------------------------------------------------------
        */

        if (!this.events[event]) {

            this.events[event] = [];

        }

        /*
        |--------------------------------------------------------------------------
        | Push Listener
        |--------------------------------------------------------------------------
        */

        this.events[event].push(callback);

    },

    /*
    |--------------------------------------------------------------------------
    | Emit Event
    |--------------------------------------------------------------------------
    */

    emit(event, payload = null) {

        /*
        |--------------------------------------------------------------------------
        | No Listeners
        |--------------------------------------------------------------------------
        */

        if (!this.events[event]) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Execute
        |--------------------------------------------------------------------------
        */

        this.events[event].forEach(callback => {

            callback(payload);

        });

    },

    /*
    |--------------------------------------------------------------------------
    | Emit Event Safely
    |--------------------------------------------------------------------------
    */

    emitSafe(event, payload = null, errorLabel = 'Builder event listener error') {

        /*
        |--------------------------------------------------------------------------
        | No Listeners
        |--------------------------------------------------------------------------
        */

        if (!this.events[event]) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Execute
        |--------------------------------------------------------------------------
        */

        this.events[event].forEach(callback => {

            try {

                callback(payload);

            } catch (error) {

                console.error(
                    errorLabel,
                    {
                        event,
                        error
                    }
                );

            }

        });

    },

    /*
    |--------------------------------------------------------------------------
    | Remove Listener
    |--------------------------------------------------------------------------
    */

    off(event, callback) {

        if (!this.events[event]) {
            return;
        }

        this.events[event] =

            this.events[event].filter(

                listener => listener !== callback

            );

    }

};
