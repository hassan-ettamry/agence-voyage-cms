window.BuilderCommands = {

    updateNodeProps(nodeId, field, value) {

        /*
        |--------------------------------------------------------------------------
        | Find Node
        |--------------------------------------------------------------------------
        */

        const node =
            Builder.findNodeById(nodeId);

        if (!node) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Ensure Props
        |--------------------------------------------------------------------------
        */

        if (!node.props) {
            node.props = {};
        }

        /*
        |--------------------------------------------------------------------------
        | Update
        |--------------------------------------------------------------------------
        */

        node.props[field] = value;

        /*
        |--------------------------------------------------------------------------
        | Events
        |--------------------------------------------------------------------------
        */

        BuilderEventBus.emit(
            'node.updated',
            {
                nodeId,
                field,
                value
            }
        );

        /*
        |--------------------------------------------------------------------------
        | History
        |--------------------------------------------------------------------------
        */

        BuilderHistory.push();

        /*
        |--------------------------------------------------------------------------
        | Render
        |--------------------------------------------------------------------------
        */

        BuilderRenderManager.requestRender();

    }

};