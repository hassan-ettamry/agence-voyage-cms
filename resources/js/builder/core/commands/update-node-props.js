window.BuilderCommands = {

    updateNodeProps(
        nodeId,
        field,
        value,
        options = {}
    ) {

        const {
            render = true
        } = options;

        /*
        |--------------------------------------------------------------------------
        | Find Node
        |--------------------------------------------------------------------------
        */

        const node =
            Builder.findNodeById(nodeId);

        if (!node) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Ensure Props
        |--------------------------------------------------------------------------
        */

        if (!node.props) {
            node.props = {};
        }

        /*
        |--------------------------------------------------------------------------
        | Update
        |--------------------------------------------------------------------------
        */

        node.props[field] = value;

        /*
        |--------------------------------------------------------------------------
        | Events
        |--------------------------------------------------------------------------
        */

        BuilderEventBus.emit(
            BuilderEvents.NODE_UPDATED,
            {
                nodeId,
                field,
                value,
                render
            }
        );

        /*
        |--------------------------------------------------------------------------
        | History
        |--------------------------------------------------------------------------
        */

        BuilderHistory.push();

    }

};
