window.BuilderSelection = {

    /*
    |--------------------------------------------------------------------------
    | Delete Selected Node
    |--------------------------------------------------------------------------
    */

    delete() {

        if (!Builder.selectedNodeId) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Remove Node
        |--------------------------------------------------------------------------
        */

        BuilderNodes.remove(
            Builder.selectedNodeId
        );

        /*
        |--------------------------------------------------------------------------
        | Push History
        |--------------------------------------------------------------------------
        */

        BuilderHistory.push();

        /*
        |--------------------------------------------------------------------------
        | Clear Selection
        |--------------------------------------------------------------------------
        */

        Builder.selectedNodeId = null;

        Builder.selectedElement = null;

        /*
        |--------------------------------------------------------------------------
        | Re-render
        |--------------------------------------------------------------------------
        */

        BuilderCanvas.render();

        /*
        |--------------------------------------------------------------------------
        | Clear Settings Panel
        |--------------------------------------------------------------------------
        */

        const panel =
            document.getElementById(
                'settings-panel'
            );

        if (panel) {
            panel.innerHTML = '';
        }

    }

};