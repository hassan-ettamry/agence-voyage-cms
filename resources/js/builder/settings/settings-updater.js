window.BuilderSettingsUpdater = {

    /*
    |--------------------------------------------------------------------------
    | Update Field
    |--------------------------------------------------------------------------
    */

    updateField(
        nodeId,
        key,
        value
    ) {

        /*
        |--------------------------------------------------------------------------
        | Find Node
        |--------------------------------------------------------------------------
        */

        const node =
            Builder.findNodeById(
                nodeId
            );

        if (!node) return;

        /*
        |--------------------------------------------------------------------------
        | Update Props
        |--------------------------------------------------------------------------
        */

        BuilderNodes.updateProps(

            nodeId,
            key,
            value

        );

        /*
        |--------------------------------------------------------------------------
        | Sync Row Columns
        |--------------------------------------------------------------------------
        */

        this.syncRowColumns(

            node,
            key,
            value

        );

        /*
        |--------------------------------------------------------------------------
        | Save History
        |--------------------------------------------------------------------------
        */

        BuilderHistory.push();

        /*
        |--------------------------------------------------------------------------
        | Re-render
        |--------------------------------------------------------------------------
        */

        BuilderCanvas.render();

    },

    /*
    |--------------------------------------------------------------------------
    | Sync Row Columns
    |--------------------------------------------------------------------------
    */

    syncRowColumns(
        node,
        key,
        value
    ) {

        if (

            node.type !== 'row'

            ||

            key !== 'columns'

        ) {

            return;

        }

        const columns =
            parseInt(value);

        /*
        |--------------------------------------------------------------------------
        | Ensure Children
        |--------------------------------------------------------------------------
        */

        if (!node.children) {

            node.children = [];

        }

        /*
        |--------------------------------------------------------------------------
        | Add Missing Columns
        |--------------------------------------------------------------------------
        */

        while (
            node.children.length < columns
        ) {

            node.children.push({

                id:
                    BuilderComponents.generateId(),

                type: 'column',

                accepts: [
                    'text',
                    'heading',
                    'button',
                    'image',
                    'container',
                    'section',
                    'row',
                    'hero'
                ],

                props: {},

                children: []

            });

        }

        /*
        |--------------------------------------------------------------------------
        | Remove Extra Columns
        |--------------------------------------------------------------------------
        */

        while (
            node.children.length > columns
        ) {

            node.children.pop();

        }

    }

};