window.BuilderSelection = {

    /*
    |--------------------------------------------------------------------------
    | Delete Selected Node
    |--------------------------------------------------------------------------
    */

    delete() {

        if (!BuilderStore.selectedNodeId) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Save Node ID
        |--------------------------------------------------------------------------
        */

        const nodeId =
            BuilderStore.selectedNodeId;

        /*
        |--------------------------------------------------------------------------
        | Remove Node
        |--------------------------------------------------------------------------
        */

        BuilderNodes.remove(
            nodeId
        );

        /*
        |--------------------------------------------------------------------------
        | Clear Selection
        |--------------------------------------------------------------------------
        */

        BuilderSelectionManager.clear({
            settings: true
        });

        /*
        |--------------------------------------------------------------------------
        | Save History
        |--------------------------------------------------------------------------
        */

        BuilderHistory.push();

        /*
        |--------------------------------------------------------------------------
        | Re-Render Canvas
        |--------------------------------------------------------------------------
        */

        BuilderRenderManager.requestRender();

    }

};
