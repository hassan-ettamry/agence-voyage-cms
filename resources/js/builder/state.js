window.Builder = {

    /*
    |--------------------------------------------------------------------------
    | UI STATE
    |--------------------------------------------------------------------------
    */

    selectedElement: null,

    selectedIndex: null,

    viewport: 'desktop',

    pageId: window.pageId || null,

    /*
    |--------------------------------------------------------------------------
    | PAGE STRUCTURE STATE
    |--------------------------------------------------------------------------
    */

    structure: [],

    /*
    |--------------------------------------------------------------------------
    | Init
    |--------------------------------------------------------------------------
    */

    init() {

        this.structure = Array.isArray(window.initialStructure)
            ? window.initialStructure
            : [];

        console.log(
            'Builder initialized:',
            this.structure
        );

    },

    /*
    |--------------------------------------------------------------------------
    | Get Structure
    |--------------------------------------------------------------------------
    */

    getStructure() {

        return this.structure;

    },

    /*
    |--------------------------------------------------------------------------
    | Set Structure
    |--------------------------------------------------------------------------
    */

    setStructure(structure = []) {

        this.structure = structure;

    },

    /*
    |--------------------------------------------------------------------------
    | Add Component
    |--------------------------------------------------------------------------
    */

    addComponent(node) {

        this.structure.push(node);

    },

    /*
    |--------------------------------------------------------------------------
    | Remove Component
    |--------------------------------------------------------------------------
    */

    removeComponent(index) {

        this.structure.splice(index, 1);

    },

    /*
    |--------------------------------------------------------------------------
    | Update Component
    |--------------------------------------------------------------------------
    */

    updateComponent(index, data) {

        if (!this.structure[index]) return;

        this.structure[index] = {
            ...this.structure[index],
            ...data
        };

    },

    /*
    |--------------------------------------------------------------------------
    | Clear
    |--------------------------------------------------------------------------
    */

    clear() {

        this.structure = [];

    }

};

/*
|--------------------------------------------------------------------------
| Init Builder
|--------------------------------------------------------------------------
*/

window.Builder.init();