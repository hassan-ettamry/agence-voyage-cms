window.BuilderCanvasSelection = {

    /*
    |--------------------------------------------------------------------------
    | Bind Selection
    |--------------------------------------------------------------------------
    */

    bind(canvas) {

        if (!canvas) return;

        canvas.addEventListener(

            'click',

            (event) => {

                const element =

                    BuilderCanvasUtils
                        .getNodeElement(
                            event.target
                        );

                if (!element) return;

                event.stopPropagation();

                /*
                |--------------------------------------------------------------------------
                | Node ID
                |--------------------------------------------------------------------------
                */

                const nodeId =
                    element.dataset.nodeId;

                if (!nodeId) return;

                /*
                |--------------------------------------------------------------------------
                | Find Node
                |--------------------------------------------------------------------------
                */

                const node =
                    Builder.findNodeById(
                        nodeId
                    );

                if (!node) return;

                /*
                |--------------------------------------------------------------------------
                | Save Selection
                |--------------------------------------------------------------------------
                */

                Builder.selectedNodeId =
                    nodeId;

                Builder.selectedElement =
                    element;

                /*
                |--------------------------------------------------------------------------
                | Clear Old Selection
                |--------------------------------------------------------------------------
                */

                BuilderCanvasUtils
                    .clearSelectionStyles();

                /*
                |--------------------------------------------------------------------------
                | Apply Selection
                |--------------------------------------------------------------------------
                */

                BuilderCanvasUtils
                    .applySelectionStyles(
                        element
                    );

                /*
                |--------------------------------------------------------------------------
                | Open Controls
                |--------------------------------------------------------------------------
                */

                BuilderSidebar.switchTab(
                    'controls'
                );

                /*
                |--------------------------------------------------------------------------
                | Settings Panel
                |--------------------------------------------------------------------------
                */

                const schema =
                    BuilderSchema.get(
                        node.type
                    );

                BuilderSettingsPanel.render(

                    node,
                    schema,
                    nodeId

                );

                /*
                |--------------------------------------------------------------------------
                | Highlight Layers
                |--------------------------------------------------------------------------
                */

                BuilderRightSidebar
                    .highlightNode(
                        nodeId
                    );

                /*
                |--------------------------------------------------------------------------
                | Show Overlay
                |--------------------------------------------------------------------------
                */

                BuilderOverlay.show(
                    element,
                    nodeId
                );

            }

        );

    }

};