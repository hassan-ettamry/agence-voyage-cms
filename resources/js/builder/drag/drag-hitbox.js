window.BuilderDragHitbox = {

    /*
    |--------------------------------------------------------------------------
    | Detect Position
    |--------------------------------------------------------------------------
    */

    detect(target, event) {

        const rect =

            target.getBoundingClientRect();

        const offsetY =

            event.clientY - rect.top;

        const ratio =

            offsetY / rect.height;

        /*
        |--------------------------------------------------------------------------
        | Before
        |--------------------------------------------------------------------------
        */

        if (ratio < 0.25) {

            return 'before';

        }

        /*
        |--------------------------------------------------------------------------
        | After
        |--------------------------------------------------------------------------
        */

        if (ratio > 0.75) {

            return 'after';

        }

        /*
        |--------------------------------------------------------------------------
        | Inside
        |--------------------------------------------------------------------------
        */

        return 'inside';

    }

};