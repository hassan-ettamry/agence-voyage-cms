window.BuilderDragState = {

    /*
    |--------------------------------------------------------------------------
    | Active Component Type
    |--------------------------------------------------------------------------
    */

    componentType: null,

    /*
    |--------------------------------------------------------------------------
    | Set Type
    |--------------------------------------------------------------------------
    */

    setType(type) {

        this.componentType = type;

    },

    /*
    |--------------------------------------------------------------------------
    | Get Type
    |--------------------------------------------------------------------------
    */

    getType() {

        return this.componentType;

    },

    /*
    |--------------------------------------------------------------------------
    | Reset
    |--------------------------------------------------------------------------
    */

    reset() {

        this.componentType = null;

    }

};