window.BuilderDragDropAction = {

    /*
    |--------------------------------------------------------------------------
    | Drop Component
    |--------------------------------------------------------------------------
    */

    drop(event) {

        event.preventDefault();

        event.stopPropagation();

        /*
        |--------------------------------------------------------------------------
        | Component Type
        |--------------------------------------------------------------------------
        */

        const type =

            event.dataTransfer.getData(
                'component-type'
            );

        if (!type) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Create Component
        |--------------------------------------------------------------------------
        */

        const component =

            BuilderComponentFactory.create(
                type
            );

        if (!component) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Find Dropzone
        |--------------------------------------------------------------------------
        */

        const dropzone =

            BuilderDragUtils
                .getDropzone(
                    event.target
                );

        /*
        |--------------------------------------------------------------------------
        | Root Drop
        |--------------------------------------------------------------------------
        */

        if (!dropzone) {

            /*
            |--------------------------------------------------------------------------
            | Add To Root
            |--------------------------------------------------------------------------
            */

            Builder.addComponent(
                component
            );

            /*
            |--------------------------------------------------------------------------
            | History
            |--------------------------------------------------------------------------
            */

            BuilderHistory.push();

            /*
            |--------------------------------------------------------------------------
            | Render
            |--------------------------------------------------------------------------
            */

            BuilderCanvas.render();

            console.log(
                'ROOT DROP:',
                component
            );

            return;

        }

        /*
        |--------------------------------------------------------------------------
        | Parent Node
        |--------------------------------------------------------------------------
        */

        const parent =

            BuilderDragUtils
                .getParentNode(
                    dropzone
                );

        if (!parent) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Validate
        |--------------------------------------------------------------------------
        */

        const isValid =

            BuilderDragValidate
                .canDrop(
                    parent,
                    type
                );

        if (!isValid) {

            console.warn(
                `${type} not allowed inside ${parent.type}`
            );

            return;

        }

        /*
        |--------------------------------------------------------------------------
        | Add Child
        |--------------------------------------------------------------------------
        */

        BuilderNodes.addChild(

            parent.id,
            component

        );

        /*
        |--------------------------------------------------------------------------
        | History
        |--------------------------------------------------------------------------
        */

        BuilderHistory.push();

        /*
        |--------------------------------------------------------------------------
        | Render
        |--------------------------------------------------------------------------
        */

        BuilderCanvas.render();

        /*
        |--------------------------------------------------------------------------
        | Debug
        |--------------------------------------------------------------------------
        */

        console.log(
            'NESTED DROP:',
            component
        );

    }

};