window.BuilderDragDrop = {

    /*
    |--------------------------------------------------------------------------
    | Start
    |--------------------------------------------------------------------------
    */

    start(event, type) {

        BuilderDragStart.start(
            event,
            type
        );

    },

    /*
    |--------------------------------------------------------------------------
    | Allow Drop
    |--------------------------------------------------------------------------
    */

    allowDrop(event) {

        event.preventDefault();

    },

    /*
    |--------------------------------------------------------------------------
    | Drop
    |--------------------------------------------------------------------------
    */

    drop(event) {

        BuilderDragDropAction.drop(
            event
        );

    }

};