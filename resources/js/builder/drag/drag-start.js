window.BuilderDragStart = {

    /*
    |--------------------------------------------------------------------------
    | Start Drag
    |--------------------------------------------------------------------------
    */

    start(event, type) {

        /*
        |--------------------------------------------------------------------------
        | Save State
        |--------------------------------------------------------------------------
        */

        BuilderDragState.setType(
            type
        );

        /*
        |--------------------------------------------------------------------------
        | Transfer Data
        |--------------------------------------------------------------------------
        */

        event.dataTransfer.setData(

            'component-type',
            type

        );

    }

};