window.BuilderDragPreview = {

    /*
    |--------------------------------------------------------------------------
    | Active Element
    |--------------------------------------------------------------------------
    */

    activeElement: null,

    /*
    |--------------------------------------------------------------------------
    | Clear Preview
    |--------------------------------------------------------------------------
    */

    clear() {

        if (!this.activeElement) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Remove Tailwind Classes
        |--------------------------------------------------------------------------
        */

        this.activeElement.classList.remove(

            'border-t-4',
            'border-b-4',

            'border-blue-500',

            'outline',
            'outline-2',
            'outline-blue-500',

            'bg-blue-50'

        );

        this.activeElement = null;

    },

    /*
    |--------------------------------------------------------------------------
    | Show Preview
    |--------------------------------------------------------------------------
    */

    show(target, position) {

        /*
        |--------------------------------------------------------------------------
        | Clear Old
        |--------------------------------------------------------------------------
        */

        this.clear();

        /*
        |--------------------------------------------------------------------------
        | Save Active
        |--------------------------------------------------------------------------
        */

        this.activeElement = target;

        /*
        |--------------------------------------------------------------------------
        | BEFORE
        |--------------------------------------------------------------------------
        */

        if (position === 'before') {

            target.classList.add(

                'border-t-4',
                'border-blue-500'

            );

        }

        /*
        |--------------------------------------------------------------------------
        | AFTER
        |--------------------------------------------------------------------------
        */

        if (position === 'after') {

            target.classList.add(

                'border-b-4',
                'border-blue-500'

            );

        }

        /*
        |--------------------------------------------------------------------------
        | INSIDE
        |--------------------------------------------------------------------------
        */

        if (position === 'inside') {

            target.classList.add(

                'outline',
                'outline-2',
                'outline-blue-500',
                'bg-blue-50'

            );

        }

    },

    /*
    |--------------------------------------------------------------------------
    | Hide Preview
    |--------------------------------------------------------------------------
    */

    hide() {

        this.clear();

    }

};