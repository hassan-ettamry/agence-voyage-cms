window.BuilderDragPreview = {

    /*
    |--------------------------------------------------------------------------
    | Active Element
    |--------------------------------------------------------------------------
    */

    activeElement: null,

    /*
    |--------------------------------------------------------------------------
    | Clear Preview
    |--------------------------------------------------------------------------
    */

    clear() {

        if (!this.activeElement) {
            return;
        }

        BuilderOverlayTheme.clearDragPreview(
            this.activeElement
        );

        this.activeElement = null;

    },

    /*
    |--------------------------------------------------------------------------
    | Show Preview
    |--------------------------------------------------------------------------
    */

    show(target, position) {

        /*
        |--------------------------------------------------------------------------
        | Clear Old
        |--------------------------------------------------------------------------
        */

        this.clear();

        /*
        |--------------------------------------------------------------------------
        | Save Active
        |--------------------------------------------------------------------------
        */

        this.activeElement = target;

        /*
        |--------------------------------------------------------------------------
        | BEFORE
        |--------------------------------------------------------------------------
        */

        if (position === 'before') {

            BuilderOverlayTheme.applyDragPreview(
                target,
                position
            );

        }

        /*
        |--------------------------------------------------------------------------
        | AFTER
        |--------------------------------------------------------------------------
        */

        if (position === 'after') {

            BuilderOverlayTheme.applyDragPreview(
                target,
                position
            );

        }

        /*
        |--------------------------------------------------------------------------
        | INSIDE
        |--------------------------------------------------------------------------
        */

        if (position === 'inside') {

            BuilderOverlayTheme.applyDragPreview(
                target,
                position
            );

        }

    },

    /*
    |--------------------------------------------------------------------------
    | Hide Preview
    |--------------------------------------------------------------------------
    */

    hide() {

        this.clear();

    }

};
