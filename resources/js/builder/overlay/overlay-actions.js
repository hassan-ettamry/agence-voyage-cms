window.BuilderOverlayActions = {

    /*
    |--------------------------------------------------------------------------
    | Move Up
    |--------------------------------------------------------------------------
    */

    moveUp(nodeId) {

        console.log(
            'MOVE UP:',
            nodeId
        );

    },

    /*
    |--------------------------------------------------------------------------
    | Move Down
    |--------------------------------------------------------------------------
    */

    moveDown(nodeId) {

        console.log(
            'MOVE DOWN:',
            nodeId
        );

    },

    /*
    |--------------------------------------------------------------------------
    | Duplicate
    |--------------------------------------------------------------------------
    */

    duplicate(nodeId) {

        console.log(
            'DUPLICATE:',
            nodeId
        );

    },

    /*
    |--------------------------------------------------------------------------
    | Edit
    |--------------------------------------------------------------------------
    */

    edit(nodeId) {

        const element =

            BuilderOverlayElements
                .getElement(nodeId);

        if (!element) return;

        element.click();

    }

};