window.BuilderStateUtils = {

    /*
    |--------------------------------------------------------------------------
    | Is Selected
    |--------------------------------------------------------------------------
    */

    isSelected(nodeId) {

        return (
            BuilderStore.selectedNodeId === nodeId
        );

    },

    /*
    |--------------------------------------------------------------------------
    | Has Selection
    |--------------------------------------------------------------------------
    */

    hasSelection() {

        return !!BuilderStore.selectedNodeId;

    }

};