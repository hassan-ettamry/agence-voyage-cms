window.BuilderComponents = {

    /*
    |--------------------------------------------------------------------------
    | Add Component
    |--------------------------------------------------------------------------
    */

    add(type) {

        const component =

            BuilderComponentFactory.create(
                type
            );

        if (!component) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Add To State
        |--------------------------------------------------------------------------
        */

        Builder.addComponent(
            component
        );

        /*
        |--------------------------------------------------------------------------
        | History
        |--------------------------------------------------------------------------
        */

        BuilderHistory.push();

        /*
        |--------------------------------------------------------------------------
        | Re-render
        |--------------------------------------------------------------------------
        */

        BuilderCanvas.render();

    }

};